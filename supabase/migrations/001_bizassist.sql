-- BizAssist schema migration for Supabase (creates tables in the default public schema)
BEGIN;

SET LOCAL search_path = public;

CREATE TABLE IF NOT EXISTS users (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL,
  email text UNIQUE NOT NULL,
  password text NOT NULL,
  role text NOT NULL CHECK (role IN ('customer','staff','admin'))
);

CREATE TABLE IF NOT EXISTS sessions (
  token text PRIMARY KEY,
  user_id integer NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  expires bigint NOT NULL
);

CREATE TABLE IF NOT EXISTS tickets (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  subject text NOT NULL,
  body text NOT NULL,
  customer_id integer NOT NULL REFERENCES users(id),
  assignee_id integer REFERENCES users(id),
  status text NOT NULL DEFAULT 'Open' CHECK(status IN ('Open','In Progress','Waiting','Resolved','Closed')),
  priority text NOT NULL CHECK(priority IN ('Low','Normal','High','Urgent')),
  category text NOT NULL,
  summary text,
  suggestion text,
  ai_source text,
  created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS messages (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ticket_id integer NOT NULL REFERENCES tickets(id) ON DELETE CASCADE,
  user_id integer NOT NULL REFERENCES users(id),
  body text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS events (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ticket_id integer NOT NULL REFERENCES tickets(id) ON DELETE CASCADE,
  actor text NOT NULL,
  description text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS articles (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title text NOT NULL,
  category text NOT NULL,
  content text NOT NULL
);

CREATE INDEX IF NOT EXISTS tickets_customer_updated ON tickets(customer_id,updated_at DESC);
CREATE INDEX IF NOT EXISTS tickets_assignee_status ON tickets(assignee_id,status);
CREATE INDEX IF NOT EXISTS messages_ticket ON messages(ticket_id,id);
CREATE INDEX IF NOT EXISTS events_ticket ON events(ticket_id,id);
CREATE INDEX IF NOT EXISTS sessions_expiry ON sessions(expires);
CREATE INDEX IF NOT EXISTS sessions_user ON sessions(user_id);

-- Enable Row Level Security (RLS) so direct browser/API access is blocked by default
ALTER TABLE users ENABLE ROW LEVEL SECURITY;
ALTER TABLE sessions ENABLE ROW LEVEL SECURITY;
ALTER TABLE tickets ENABLE ROW LEVEL SECURITY;
ALTER TABLE messages ENABLE ROW LEVEL SECURITY;
ALTER TABLE events ENABLE ROW LEVEL SECURITY;
ALTER TABLE articles ENABLE ROW LEVEL SECURITY;

-- Revoke direct permissions from public API roles for security
DO $$
DECLARE api_role text;
BEGIN
  FOREACH api_role IN ARRAY ARRAY['anon','authenticated'] LOOP
    IF EXISTS(SELECT 1 FROM pg_roles WHERE rolname=api_role) THEN
      EXECUTE format('REVOKE ALL ON TABLE users, sessions, tickets, messages, events, articles FROM %I', api_role);
      EXECUTE format('REVOKE ALL ON ALL SEQUENCES IN SCHEMA public FROM %I', api_role);
    END IF;
  END LOOP;
END $$;

COMMIT;
